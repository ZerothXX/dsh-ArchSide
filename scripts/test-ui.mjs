import { chromium } from 'playwright';
import { spawn } from 'node:child_process';
import { mkdir, mkdtemp, copyFile, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import assert from 'node:assert/strict';
const workspace = await mkdtemp(path.join(tmpdir(), 'archside-ui-'));
await copyFile('examples/architecture.md', path.join(workspace, 'architecture.md'));
const port = 4181;
const server = spawn(process.execPath, ['--import', 'tsx', 'scripts/preview.mjs'], { env: { ...process.env, PORT: String(port), ARCHSIDE_PREVIEW_WORKSPACE: workspace }, stdio: ['ignore', 'pipe', 'pipe'], windowsHide: true });
let serverLog = ''; server.stdout.on('data', chunk => serverLog += chunk); server.stderr.on('data', chunk => serverLog += chunk);
let browser;
try {
  for (let i = 0; i < 60; i++) { try { if ((await fetch(`http://127.0.0.1:${port}/api/snapshot`)).ok) break; } catch {} await new Promise(r => setTimeout(r, 200)); }
  browser = await chromium.launch({ channel: 'chrome', headless: true });
  const page = await browser.newPage({ viewport: { width: 1512, height: 982 }, deviceScaleFactor: 1 });
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
  await page.goto(`http://127.0.0.1:${port}`);
  await page.getByTestId('node-structure').waitFor();
  await mkdir('artifacts', { recursive: true });
  await page.screenshot({ path: 'artifacts/overview-simple.png' });
  await page.getByRole('button', { name: '1 需求与结构 节点操作', exact: true }).click();
  await page.getByRole('menuitem', { name: '选中 @' }).click();
  await page.waitForFunction(() => document.querySelector('#preview-draft').value.includes('@(1 需求与结构)'));
  assert.match(await page.getByRole('textbox', { name: '预览对话输入框' }).inputValue(), /@\(1 需求与结构\)/);
  await page.getByRole('button', { name: '详细', exact: true }).click();
  await page.getByTestId('node-markdown').waitFor();
  assert.equal(await page.getByTestId('node-structure').count(), 0);
  assert.equal(await page.locator('.as-group').count(), 0);
  assert.equal(await page.locator('.as-edges g[data-relationship="explicit"]').count(), 11, 'all MD relationships should remain visible');
  assert.equal(await page.locator('.as-edges g[data-relationship="structural"]').count(), 4);
  assert.equal(await page.locator('.as-edges g[data-relationship="structural"] path[marker-end]').count(), 0, 'hierarchy must not look like data-flow arrows');
  assert.ok(await page.locator('.as-project-heading').evaluate(e => e.getBoundingClientRect().height < 100), 'heading should leave more space for the graph');
  await page.getByTestId('node-markdown').hover();
  assert.ok(await page.locator('.as-edges g[opacity="0.14"]').count(), 'hover should emphasize related paths');
  await page.mouse.move(100, 70);
  await page.screenshot({ path: 'artifacts/overview-detailed.png' });
  const initialDetailPosition = await page.getByTestId('node-markdown').evaluate(e => [e.style.left, e.style.top]);
  const detailBox = await page.getByTestId('node-markdown').boundingBox();
  await page.mouse.move(detailBox.x + 22, detailBox.y + 15); await page.mouse.down();
  await page.mouse.move(detailBox.x + 90, detailBox.y + 75, { steps: 6 }); await page.mouse.up();
  assert.notDeepEqual(await page.getByTestId('node-markdown').evaluate(e => [e.style.left, e.style.top]), initialDetailPosition);
  await page.getByRole('button', { name: '按关系重新布局', exact: true }).click();
  assert.deepEqual(await page.getByTestId('node-markdown').evaluate(e => [e.style.left, e.style.top]), initialDetailPosition);
  await page.getByRole('button', { name: '1.1 架构 Markdown 节点操作', exact: true }).click();
  await page.getByRole('menuitem', { name: '扩展', exact: true }).click();
  await page.getByTestId('node-heading-format').waitFor();
  assert.equal(await page.locator('.as-group').count(), 0);
  assert.ok(await page.getByTestId('node-markdown').evaluate(e => e.classList.contains('highlighted')));
  await page.getByRole('button', { name: '全部展开', exact: true }).click();
  await page.getByRole('button', { name: '全部收起', exact: true }).waitFor();
  await page.getByRole('button', { name: '适应画布', exact: true }).click();
  await page.mouse.move(100, 70);
  await page.screenshot({ path: 'artifacts/chapter-expanded.png' });
  await page.getByTestId('node-heading-format').click({ button: 'right' });
  await page.getByRole('menuitem', { name: '扩展', exact: true }).click();
  await page.getByTestId('node-detail').waitFor();
  assert.ok(await page.getByTestId('node-detail').locator('table').count());
  assert.equal(await page.getByRole('button', { name: '第三层 节点详情', exact: true }).count(), 1);
  await page.screenshot({ path: 'artifacts/node-detail.png' });
  await page.getByRole('button', { name: '选中节点', exact: false }).click();
  await page.waitForFunction(() => document.querySelector('#preview-draft').value.includes('@(1.1.1 标题与节点规范)'));
  await page.getByRole('button', { name: '第二层 章内架构', exact: true }).click();
  await page.getByTestId('node-heading-format').waitFor();
  await page.getByRole('button', { name: '第一层 项目总览', exact: true }).click();
  await page.getByRole('button', { name: '简洁', exact: true }).click();
  await page.getByTestId('node-structure').waitFor();
  const oldPosition = await page.getByTestId('node-structure').evaluate(e => ({ x: e.style.left, y: e.style.top }));
  const box = await page.getByTestId('node-structure').boundingBox();
  await page.mouse.move(box.x + 30, box.y + 22); await page.mouse.down(); await page.mouse.move(box.x + 75, box.y + 70, { steps: 7 }); await page.mouse.up();
  await page.waitForTimeout(650);
  const newPosition = await page.getByTestId('node-structure').evaluate(e => ({ x: e.style.left, y: e.style.top }));
  assert.notDeepEqual(newPosition, oldPosition);
  await page.reload();
  await page.getByTestId('node-structure').waitFor();
  assert.deepEqual(await page.getByTestId('node-structure').evaluate(e => ({ x: e.style.left, y: e.style.top })), newPosition);
  await page.getByRole('button', { name: '查找节点', exact: true }).click();
  await page.getByRole('textbox', { name: '搜索架构节点' }).fill('src/core/markdown.ts');
  await page.locator('.as-results button').filter({ hasText: '1.1.1 标题与节点规范' }).click();
  await page.getByTestId('node-heading-format').waitFor();
  assert.ok(await page.getByTestId('node-heading-format').evaluate(e => e.classList.contains('highlighted')));
  await page.getByRole('button', { name: '放大', exact: true }).click();
  await page.getByRole('button', { name: '缩小', exact: true }).click();
  await page.setViewportSize({ width: 1100, height: 800 });
  await page.screenshot({ path: 'artifacts/narrow-sidebar.png' });
  const panelOverflow = await page.getByTestId('architecture-panel').evaluate(e => e.scrollWidth > e.clientWidth);
  assert.equal(panelOverflow, false);
  assert.deepEqual(errors, [], `Browser errors: ${errors.join('\n')}`);
  console.log('UI verified: three levels, chapter focus, @ draft, multiple references, context menu, explanation toggle, drag persistence, search, zoom and narrow sidebar.');
  console.log('Screenshots: artifacts/overview-simple.png, overview-detailed.png, chapter-expanded.png, node-detail.png, narrow-sidebar.png');
} catch (error) { console.error(serverLog); throw error; }
finally { await browser?.close(); server.kill(); await new Promise(r => server.once('exit', r)); await rm(workspace, { recursive: true, force: true }); }
